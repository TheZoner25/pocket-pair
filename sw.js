/* Pocket Pair service worker. It only shows notifications and opens the app when one is tapped.
   It caches nothing, so every visit still loads the newest version from GitHub Pages. */
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));

self.addEventListener('push', e => {
  let d = {};
  try { d = e.data ? e.data.json() : {}; } catch (x) { d = { body: e.data ? e.data.text() : '' }; }
  e.waitUntil(self.registration.showNotification(d.title || 'Pocket Pair', {
    body: d.body || '',
    tag: d.tag || 'pair',          // a new heart replaces the last heart instead of stacking up
    renotify: true,
    icon: 'icons/icon-192.png',
    badge: 'icons/badge-72.png',
    data: { url: d.url || './' }
  }));
});

self.addEventListener('notificationclick', e => {
  e.notification.close();
  const url = new URL((e.notification.data && e.notification.data.url) || './', self.registration.scope).href;
  e.waitUntil(self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(list => {
    for (const c of list) if (c.url.startsWith(self.registration.scope) && 'focus' in c) return c.focus();
    return self.clients.openWindow(url);
  }));
});
